/** Mechanically binds server execution to the exact reviewed artifacts. No env or DB. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const remediation = readFileSync(new URL("scripts/sql/remediate-991-checks.sql", root), "utf8");
const canonical = readFileSync(new URL("packages/database/prisma/migrations/20261007_ai_worker_provisioning_boundary/migration.sql", root), "utf8");
const hash = text => createHash("sha256").update(text).digest("hex");
if (hash(remediation) !== "1c07112091af372cfad73488c822cd98fab271b05896458495369c3b0c8f1b6e"
  || hash(canonical) !== "55f5aa9294078d52a88a505b5480f41ed15e691f0175c7df1e3f58a0cbe3b70d") {
  throw new Error("Reviewed #991 artifact checksum mismatch");
}
const output = '// Generated by scripts/generate-remediate-991-sql.mjs; do not hand-edit.\nimport "server-only";\n'
  + `export const REVIEWED_REMEDIATION = ${JSON.stringify(remediation)};\n`
  + `export const REVIEWED_CANONICAL_MIGRATION = ${JSON.stringify(canonical)};\n`;
const target = new URL("src/lib/remediate-991-sql-generated.ts", root);
if (process.argv[2] === "--write") writeFileSync(target, output);
else if (readFileSync(target, "utf8") !== output) throw new Error("Generated #991 SQL is stale");
console.log(`Reviewed #991 artifacts and generated binding verified (${fileURLToPath(target)})`);
